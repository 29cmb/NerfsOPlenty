package xyz.devcmb.nerfsoplenty.nerf

/**
 * An empty nerf class
 *
 * These should be used when you're checking if a player has it elsewhere but it doesn't do anything on its own.
 *
 * Ex: Useful for when you're modifying render state in a mixin
 */
class EmptyNerf(name: String, listed: Boolean = true) : Nerf(name, listed)